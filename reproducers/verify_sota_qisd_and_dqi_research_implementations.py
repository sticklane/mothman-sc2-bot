def optimal_dqi_tridiagonal_weights(m: int, ell: int) -> Tuple[np.ndarray, float]:
    """Jordan et al. 2024 (arXiv:2408.08292 Theorem 4.1) & BankNatchapol/DQI-Circuit
    src/dqi/qiskit/initialization/calculate_w.py principal eigenvector of A^{(m, ell)}."""
    dim = ell + 1
    tridiag = np.zeros((dim, dim), dtype=np.float64)
    for k in range(ell):
        off = math.sqrt((k + 1) * (m - k))
        tridiag[k, k + 1] = off
        tridiag[k + 1, k] = off
    eigvals, eigvecs = np.linalg.eigh(tridiag)
    lam_max = float(eigvals[-1])
    w = np.abs(eigvecs[:, -1])
    w /= np.linalg.norm(w)
    return w, lam_max


def build_bounded_distance_syndrome_table(bt: np.ndarray, ell: int) -> Dict[int, int]:
    """Canonical minimum-weight bounded-distance coset-leader lookup Dec(s) = y
    for wt(y) <= ell, mapping syndrome bitmask s -> error bitmask y."""
    n_rows, m_cols = bt.shape
    table: Dict[int, int] = {}
    # Iterate in strictly non-decreasing Hamming weight so lowest-weight leader wins:
    all_masks = sorted(range(1 << m_cols), key=lambda mask: mask.bit_count())
    for y_mask in all_masks:
        if y_mask.bit_count() > ell:
            break
        y_vec = np.array([(y_mask >> i) & 1 for i in range(m_cols)], dtype=np.int64)
        s_vec = (bt @ y_vec) % 2
        s_mask = sum(int(s_vec[j]) << j for j in range(n_rows))
        if s_mask not in table:
            table[s_mask] = y_mask
    return table


def simulate_dqi_circuit_aer(
    bt: np.ndarray,
    ell: int,
    weights: Sequence[float],
    v_bits: Sequence[int],
) -> Dict[str, float]:
    """Builds and simulates the full (m + n)-qubit DQI quantum circuit on AerSimulator:
      1. Prepares weighted Dicke error superposition sum_{k=0}^ell w_k |D_k^m>_y |0^n>_s
      2. Applies target XORSAT phase (-1)^{v . y} via Z gates on |y>
      3. Computes syndrome |s> = |B^T y> via CNOT fanout (CX gates)
      4. Uncomputes |y> -> |y xor Dec(s)> via coherent bounded-distance syndrome decoder
      5. Evaluates reduced syndrome purity Tr(rho_s^2) and leak probability Pr[y != 0^m]
      6. Applies Walsh-Hadamard H^{otimes n} on |s> and computes E[# satisfied constraints]
    """
    n_rows, m_cols = bt.shape
    total_q = m_cols + n_rows
    y_q = list(range(m_cols))
    s_q = list(range(m_cols, m_cols + n_rows))

    # Build normalized initial Dicke statevector on y_q (m_cols qubits):
    y_amp = np.zeros(1 << m_cols, dtype=np.complex128)
    for k in range(ell + 1):
        comb_k = math.comb(m_cols, k)
        amp_k = float(weights[k]) / math.sqrt(comb_k)
        for mask in range(1 << m_cols):
            if mask.bit_count() == k:
                y_amp[mask] = amp_k

    qc = QuantumCircuit(total_q)
    qc.initialize(y_amp, y_q)

    # Phase (-1)^{v . y}:
    for i in range(m_cols):
        if v_bits[i] == 1:
            qc.z(y_q[i])

    # Coherent syndrome compute |y>|0^n> -> |y>|B^T y>:
    for r in range(n_rows):
        for i in range(m_cols):
            if bt[r, i] == 1:
                qc.cx(y_q[i], s_q[r])

    # Coherent bounded-distance decoder uncompute |y>|s> -> |y xor Dec(s)>|s>:
    dec_table = build_bounded_distance_syndrome_table(bt, ell)
    for s_mask, y_leader_mask in dec_table.items():
        if y_leader_mask == 0:
            continue
        zero_ctrls = [s_q[r] for r in range(n_rows) if ((s_mask >> r) & 1) == 0]
        for q in zero_ctrls:
            qc.x(q)
        for i in range(m_cols):
            if ((y_leader_mask >> i) & 1) == 1:
                qc.mcx(s_q, y_q[i])
        for q in zero_ctrls:
            qc.x(q)

    # Snapshot state before H^{otimes n} to measure entanglement leak & reduced purity:
    sim = AerSimulator(method="statevector")
    qc_pre_h = qc.copy()
    qc_pre_h.save_statevector()
    sv_pre = Statevector(sim.run(qc_pre_h).result().get_statevector(qc_pre_h))
    probs_pre = np.abs(np.asarray(sv_pre)) ** 2

    mask_y = (1 << m_cols) - 1
    leak_prob = float(
        sum(p for idx, p in enumerate(probs_pre) if (idx & mask_y) != 0)
    )
    rho_s = partial_trace(sv_pre, y_q)
    purity_s = float(np.real(np.trace(rho_s.data @ rho_s.data)))

    # Complete DQI interference via H^{otimes n} on s_q:
    qc_post = qc.copy()
    for q in s_q:
        qc_post.h(q)
    qc_post.save_statevector()
    sv_post = np.asarray(sim.run(qc_post).result().get_statevector(qc_post))
    probs_post = np.abs(sv_post) ** 2

    # Marginal distribution over x in GF(2)^n (stored in s_q bits) and E[satisfied]:
    x_probs = np.zeros(1 << n_rows, dtype=np.float64)
    for full_idx, p in enumerate(probs_post):
        if p > 0.0:
            x_probs[full_idx >> m_cols] += float(p)

    b_mat = bt.T  # m_cols x n_rows
    v_arr = np.asarray(v_bits, dtype=np.int64)
    exp_sat = 0.0
    for x_mask, px in enumerate(x_probs):
        if px > 0.0:
            x_vec = np.array([(x_mask >> r) & 1 for r in range(n_rows)], dtype=np.int64)
            bx = (b_mat @ x_vec) % 2
            sat_count = int(np.sum(bx == v_arr))
            exp_sat += px * sat_count

    return {
        "leak_prob": leak_prob,
        "reduced_syndrome_purity": purity_s,
        "expected_satisfied_constraints": exp_sat,
        "satisfied_fraction": exp_sat / float(m_cols),
    }


def verify_early_mbu_dqi_erasure_aer() -> Dict[str, float]:
    """Verifies on AerSimulator for [7, 4, 3] Hamming (ell = 1) that Early-MBU
    mid-circuit X-basis measurement (H + M_X) on the 7-qubit error register |y>
    followed by syndrome-decoded Pauli-Z phase correction on |s> uses ZERO
    decoder uncompute Toffolis and achieves exact fidelity 1.000000000000000
    across all 2^7 = 128 X-measurement branches against unitary DQI!"""
    bt = HAMMING_7_4_3_BT
    n_rows, m_cols = bt.shape  # 3, 7
    w_opt, _ = optimal_dqi_tridiagonal_weights(m_cols, 1)
    v_bits = [1, 0, 1, 1, 0, 1, 0]
    dec_table = build_bounded_distance_syndrome_table(bt, 1)

    # Reference pure n-qubit syndrome state produced by unitary DQI before H^{otimes n}:
    total_q = m_cols + n_rows
    y_q = list(range(m_cols))
    s_q = list(range(m_cols, total_q))
    y_amp = np.zeros(1 << m_cols, dtype=np.complex128)
    for k in range(2):
        amp_k = float(w_opt[k]) / math.sqrt(math.comb(m_cols, k))
        for mask in range(1 << m_cols):
            if mask.bit_count() == k:
                y_amp[mask] = amp_k

    qc_unitary = QuantumCircuit(total_q)
    qc_unitary.initialize(y_amp, y_q)
    for i in range(m_cols):
        if v_bits[i] == 1:
            qc_unitary.z(y_q[i])
    for r in range(n_rows):
        for i in range(m_cols):
            if bt[r, i] == 1:
                qc_unitary.cx(y_q[i], s_q[r])
    for s_mask, y_leader_mask in dec_table.items():
        if y_leader_mask == 0:
            continue
        zero_ctrls = [s_q[r] for r in range(n_rows) if ((s_mask >> r) & 1) == 0]
        for q in zero_ctrls:
            qc_unitary.x(q)
        for i in range(m_cols):
            if ((y_leader_mask >> i) & 1) == 1:
                qc_unitary.mcx(s_q, y_q[i])
        for q in zero_ctrls:
            qc_unitary.x(q)

    sim = AerSimulator(method="statevector")
    qc_u_run = qc_unitary.copy()
    qc_u_run.save_statevector()
    sv_u_full = np.asarray(sim.run(qc_u_run).result().get_statevector(qc_u_run))
    # Extract pure syndrome state on y == 0^m:
    psi_ref_s = np.array([sv_u_full[s_mask << m_cols] for s_mask in range(1 << n_rows)])

    # Early-MBU circuit: NO Toffoli decoder uncompute on |y>! Instead apply H^{otimes m}
    # on |y>, project onto each X-measurement outcome b in {0,1}^m, and apply phase
    # (-1)^{b . Dec(s)} to |s> (classical LUT -> diagonal phase / Pauli frame!):
    qc_mbu_pre = QuantumCircuit(total_q)
    qc_mbu_pre.initialize(y_amp, y_q)
    for i in range(m_cols):
        if v_bits[i] == 1:
            qc_mbu_pre.z(y_q[i])
    for r in range(n_rows):
        for i in range(m_cols):
            if bt[r, i] == 1:
                qc_mbu_pre.cx(y_q[i], s_q[r])
    for q in y_q:
        qc_mbu_pre.h(q)
    qc_mbu_pre.save_statevector()
    sv_mbu = np.asarray(sim.run(qc_mbu_pre).result().get_statevector(qc_mbu_pre))

    min_branch_fidelity = 1.0
    total_branch_prob = 0.0
    for b_mask in range(1 << m_cols):
        branch_vec = np.array(
            [sv_mbu[(s_mask << m_cols) | b_mask] for s_mask in range(1 << n_rows)],
            dtype=np.complex128,
        )
        p_branch = float(np.real(np.vdot(branch_vec, branch_vec)))
        total_branch_prob += p_branch
        if p_branch > 1e-14:
            branch_norm = branch_vec / math.sqrt(p_branch)
            # Apply Early-MBU Pauli phase correction (-1)^{b . Dec(s)}:
            for s_mask in range(1 << n_rows):
                y_leader = dec_table[s_mask]
                if (b_mask & y_leader).bit_count() & 1:
                    branch_norm[s_mask] *= -1.0
            fid = float(state_fidelity(Statevector(branch_norm), Statevector(psi_ref_s)))
            min_branch_fidelity = min(min_branch_fidelity, fid)

    assert min_branch_fidelity > 1.0 - 1e-13, (
        f"Early-MBU branch fidelity dropped: {min_branch_fidelity}"
    )
    return {
        "total_branch_probability": total_branch_prob,
        "min_branch_fidelity_across_all_128_outcomes": min_branch_fidelity,
        "max_infidelity": max(0.0, 1.0 - min_branch_fidelity),
        "uncompute_toffoli_gates_early_mbu": 0,
    }


def verify_dqi_radius_z3() -> Dict[str, object]:
    """Z3 verification of unique-decoding injectivity iff 2 * ell < d_perp on
    [7, 4, 3] Hamming (d_perp = 3) and [8, 2, 5] (d_perp = 5)."""
    def check_injectivity(bt: np.ndarray, ell: int) -> Tuple[str, Dict[str, List[int]] | None]:
        n_rows, m_cols = bt.shape
        y1 = [z3.Bool(f"y1_{i}") for i in range(m_cols)]
        y2 = [z3.Bool(f"y2_{i}") for i in range(m_cols)]
        s = z3.Solver()
        s.add(z3.Sum([z3.If(b, 1, 0) for b in y1]) <= ell)
        s.add(z3.Sum([z3.If(b, 1, 0) for b in y2]) <= ell)
        s.add(z3.Or(*[y1[i] != y2[i] for i in range(m_cols)]))
        for r in range(n_rows):
            syn1 = z3.BoolVal(False)
            syn2 = z3.BoolVal(False)
            for i in range(m_cols):
                if bt[r, i] == 1:
                    syn1 = z3.Xor(syn1, y1[i])
                    syn2 = z3.Xor(syn2, y2[i])
            s.add(syn1 == syn2)
        res = s.check()
        if res == z3.sat:
            mdl = s.model()
            return "sat", {
                "y1": [int(bool(mdl.eval(b, model_completion=True))) for b in y1],
                "y2": [int(bool(mdl.eval(b, model_completion=True))) for b in y2],
            }
        return str(res), None

    st_743_1, _ = check_injectivity(HAMMING_7_4_3_BT, 1)
    st_743_2, wit_743_2 = check_injectivity(HAMMING_7_4_3_BT, 2)
    st_825_2, _ = check_injectivity(CODE_8_2_5_BT, 2)
    st_825_3, wit_825_3 = check_injectivity(CODE_8_2_5_BT, 3)

    assert st_743_1 == "unsat" and st_743_2 == "sat"
    assert st_825_2 == "unsat" and st_825_3 == "sat"

    return {
        "hamming_7_4_3_ell1_collision_z3": st_743_1,
        "hamming_7_4_3_ell2_collision_z3": st_743_2,
        "hamming_7_4_3_ell2_collision_witness": wit_743_2,
        "code_8_2_5_ell2_collision_z3": st_825_2,
        "code_8_2_5_ell3_collision_z3": st_825_3,
        "code_8_2_5_ell3_collision_witness": wit_825_3,
    }


