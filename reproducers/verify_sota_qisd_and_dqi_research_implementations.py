def verify_qm4ri_strassen_and_jordan_split_z3() -> Dict[str, object]:
    """Z3 equivalence proofs over GF(2) for:
      (a) Two-level recursive 4x4 Strassen-Kronrod block multiplication (49 TempANDs)
          vs naive 4x4x4 = 64 TempAND matrix multiplication across all 2^32 (A, B) pairs.
      (b) Jordan-split syndrome-only back-substitution (updating above-diagonal rows
          ONLY on the syndrome column) vs full Gauss-Jordan RREF on 4x4 invertible systems.
    """
    def xor_list(xs: Sequence[z3.BoolRef]) -> z3.BoolRef:
        acc = z3.BoolVal(False)
        for x in xs:
            acc = z3.Xor(acc, x)
        return acc

    def mat_xor(x: List[List[z3.BoolRef]], y: List[List[z3.BoolRef]]) -> List[List[z3.BoolRef]]:
        n = len(x)
        return [[z3.Xor(x[r][c], y[r][c]) for c in range(n)] for r in range(n)]

    and_counter = [0]

    def strassen_gf2(
        a: List[List[z3.BoolRef]], b: List[List[z3.BoolRef]]
    ) -> List[List[z3.BoolRef]]:
        n = len(a)
        if n == 1:
            and_counter[0] += 1
            return [[z3.And(a[0][0], b[0][0])]]
        half = n // 2
        a11 = [row[:half] for row in a[:half]]
        a12 = [row[half:] for row in a[:half]]
        a21 = [row[:half] for row in a[half:]]
        a22 = [row[half:] for row in a[half:]]
        b11 = [row[:half] for row in b[:half]]
        b12 = [row[half:] for row in b[:half]]
        b21 = [row[:half] for row in b[half:]]
        b22 = [row[half:] for row in b[half:]]

        # Over characteristic 2 (subtraction == addition == XOR):
        m1 = strassen_gf2(mat_xor(a11, a22), mat_xor(b11, b22))
        m2 = strassen_gf2(mat_xor(a21, a22), b11)
        m3 = strassen_gf2(a11, mat_xor(b12, b22))
        m4 = strassen_gf2(a22, mat_xor(b21, b11))
        m5 = strassen_gf2(mat_xor(a11, a12), b22)
        m6 = strassen_gf2(mat_xor(a21, a11), mat_xor(b11, b12))
        m7 = strassen_gf2(mat_xor(a12, a22), mat_xor(b21, b22))

        c11 = mat_xor(mat_xor(m1, m4), mat_xor(m5, m7))
        c12 = mat_xor(m3, m5)
        c21 = mat_xor(m2, m4)
        c22 = mat_xor(mat_xor(m1, m2), mat_xor(m3, m6))

        top = [c11[r] + c12[r] for r in range(half)]
        bot = [c21[r] + c22[r] for r in range(half)]
        return top + bot

    a_sym = [[z3.Bool(f"a_{r}_{c}") for c in range(4)] for r in range(4)]
    b_sym = [[z3.Bool(f"b_{r}_{c}") for c in range(4)] for r in range(4)]
    c_strassen = strassen_gf2(a_sym, b_sym)
    assert and_counter[0] == 49, f"Expected 49 TempANDs, got {and_counter[0]}"

    c_naive = [
        [xor_list([z3.And(a_sym[r][k], b_sym[k][c]) for k in range(4)]) for c in range(4)]
        for r in range(4)
    ]
    s_mul = z3.Solver()
    s_mul.add(
        z3.Or(*[c_strassen[r][c] != c_naive[r][c] for r in range(4) for c in range(4)])
    )
    res_mul = s_mul.check()
    assert res_mul == z3.unsat, "4x4 GF(2) Strassen-Kronrod multiplication failed Z3 equivalence"

    # (b) 4x4 Jordan-split syndrome-only back-substitution vs full Gauss-Jordan:
    h_sym = [[z3.Bool(f"h_{r}_{c}") for c in range(4)] for r in range(4)]
    s_vec = [z3.Bool(f"sv_{r}") for r in range(4)]

    aug_full = [[h_sym[r][c] for c in range(4)] + [s_vec[r]] for r in range(4)]
    aug_jsplit = [[h_sym[r][c] for c in range(4)] + [s_vec[r]] for r in range(4)]

    for x in range(4):
        for i in range(x + 1, 4):
            sw_f = z3.And(z3.Not(aug_full[x][x]), aug_full[i][x])
            aug_full[x][x] = z3.Xor(aug_full[x][x], sw_f)
            for j in range(x + 1, 5):
                aug_full[x][j] = z3.Xor(aug_full[x][j], z3.And(sw_f, aug_full[i][j]))

            sw_j = z3.And(z3.Not(aug_jsplit[x][x]), aug_jsplit[i][x])
            aug_jsplit[x][x] = z3.Xor(aug_jsplit[x][x], sw_j)
            for j in range(x + 1, 5):
                aug_jsplit[x][j] = z3.Xor(aug_jsplit[x][j], z3.And(sw_j, aug_jsplit[i][j]))

        # Full Gauss-Jordan updates all i != x across all j in x+1..4:
        for i in range(4):
            if i == x:
                continue
            fac = aug_full[i][x]
            for j in range(x + 1, 5):
                aug_full[i][j] = z3.Xor(aug_full[i][j], z3.And(fac, aug_full[x][j]))
            aug_full[i][x] = z3.BoolVal(False)

        # Forward Gaussian elimination in Jordan-split updates ONLY below-diagonal i > x:
        for i in range(x + 1, 4):
            fac = aug_jsplit[i][x]
            for j in range(x + 1, 5):
                aug_jsplit[i][j] = z3.Xor(aug_jsplit[i][j], z3.And(fac, aug_jsplit[x][j]))
            aug_jsplit[i][x] = z3.BoolVal(False)

    # Reverse Jordan-split back-substitution updates ONLY syndrome col 4!
    for x in range(3, -1, -1):
        for i in range(x):
            aug_jsplit[i][4] = z3.Xor(
                aug_jsplit[i][4], z3.And(aug_jsplit[i][x], aug_jsplit[x][4])
            )

    ns_full = z3.And(*[aug_full[d][d] for d in range(4)])
    ns_jsplit = z3.And(*[aug_jsplit[d][d] for d in range(4)])

    s_js = z3.Solver()
    s_js.add(
        z3.Or(
            ns_full != ns_jsplit,
            z3.And(
                ns_full,
                z3.Or(*[aug_full[r][4] != aug_jsplit[r][4] for r in range(4)]),
            ),
        )
    )
    res_js = s_js.check()
    assert res_js == z3.unsat, "Jordan-split back-substitution failed Z3 equivalence"

    return {
        "strassen_4x4_tempands": 49,
        "naive_4x4_tempands": 64,
        "strassen_4x4_z3_inequivalence": str(res_mul),
        "jordan_split_4x4_z3_inequivalence": str(res_js),
    }


